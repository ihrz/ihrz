/// Fake-hack profile: IP, email, password. Index picks mirror the TS
/// `crypto.randomInt` calls; in prod the RNG is the OS-seeded ChaCha CSPRNG
/// (`rand::thread_rng`), the Rust equivalent of node's `crypto` module.
pub struct HackProfile {
    pub ip: String,
    pub email: String,
    pub password: String,
}

/// Mirrors `generateRandomNumber` (4 crypto random bytes as a u32 string).
pub fn hack_number(rng: &mut impl rand::Rng) -> String {
    rng.gen::<u32>().to_string()
}

/// Index pick. Mirrors one `crypto.randomInt(0, list.length)` call.
fn pick(rng: &mut impl rand::Rng, list: &[&str]) -> String {
    list[rng.gen_range(0..list.len())].to_string()
}

/// Build the fake-hack profile from the `!hack.ts` wordlists.
pub fn hack_profile(rng: &mut impl rand::Rng) -> HackProfile {
    let ip = (0..4)
        .map(|_| pick(rng, HACK_IP_PARTS))
        .collect::<Vec<_>>()
        .join(".");
    let username = format!("{}{}", pick(rng, HACKER_NAMES), hack_number(rng));
    HackProfile {
        email: format!("{}@{}", username, pick(rng, HACKER_DOMAINS)),
        password: pick(rng, HACKER_PASSWORDS),
        ip,
    }
}

/// Fill hack_embed_description. Mirrors the /g `${victim.id}` +
/// `${interaction.user.id}` replaces.
pub fn hack_description(template: &str, victim_id: u64, author_id: u64) -> String {
    template
        .replace("${victim.id}", &victim_id.to_string())
        .replace("${interaction.user.id}", &author_id.to_string())
}

#[poise::command(slash_command, prefix_command, category = "fun", rename = "hack")]
pub async fn hack(
    ctx: Ctx<'_>,
    #[description = "Member"] user: Option<poise::serenity_prelude::User>,
) -> Result<(), anyhow::Error> {
    if fun_guard(&ctx).await {
        return Ok(());
    }
    let code = crate::db::guild_lang(&ctx.data().pool, ctx.guild_id().map(|g| g.get())).await;
    let f = |k: &str, fb: &str| crate::lang::get(&code, k).unwrap_or_else(|| fb.to_string());
    let profile = hack_profile(&mut rand::thread_rng());
    // Mirrors the prefix `|| interaction.author` fallback in `!hack.ts`
    // (slash without a target falls back the same way instead of throwing
    // on a null victim).
    let victim = user.as_ref().unwrap_or_else(|| ctx.author());
    let embed = poise::serenity_prelude::CreateEmbed::default()
        .colour(0x800000u32)
        .description(hack_description(
            &f(
                "hack_embed_description",
                "<@${victim.id}> hacked by <@${interaction.user.id}>!",
            ),
            victim.id.get(),
            ctx.author().id.get(),
        ))
        .field(
            f("hack_embed_fields_ip", "IP"),
            format!("`{}`", profile.ip),
            false,
        )
        .field(
            f("hack_embed_fields_email", "Email"),
            format!("`{}`", profile.email),
            false,
        )
        .field(
            f("hack_embed_fields_password", "Password"),
            format!("`{}`", profile.password),
            false,
        )
        .timestamp(poise::serenity_prelude::Timestamp::now());
    ctx.send(poise::CreateReply::default().embed(embed)).await?;
    Ok(())
}

#[cfg(test)]
mod hack_tests {
    use super::*;
    use rand::SeedableRng;

    fn seeded() -> rand::rngs::StdRng {
        rand::rngs::StdRng::seed_from_u64(7)
    }

    #[test]
    fn wordlists_match_ts_lengths() {
        assert_eq!(HACK_IP_PARTS.len(), 32);
        assert_eq!(HACKER_NAMES.len(), 221);
        assert_eq!(HACKER_DOMAINS.len(), 113);
        assert_eq!(HACKER_PASSWORDS.len(), 92);
    }

    #[test]
    fn profile_shapes_match_ts() {
        let p = hack_profile(&mut seeded());
        let parts: Vec<&str> = p.ip.split('.').collect();
        assert_eq!(parts.len(), 4);
        for part in parts {
            assert!(HACK_IP_PARTS.contains(&part), "unknown ip part {part}");
        }
        let (local, domain) = p.email.split_once('@').expect("email has @");
        assert!(HACKER_DOMAINS.contains(&domain));
        assert!(HACKER_NAMES.iter().any(|n| local.starts_with(n)));
        assert!(local.chars().last().is_some_and(|c| c.is_ascii_digit()));
        assert!(HACKER_PASSWORDS.contains(&p.password.as_str()));
    }

    #[test]
    fn description_fills_ids() {
        assert_eq!(
            hack_description("<@${victim.id}> hacked by <@${interaction.user.id}>!", 1, 2),
            "<@1> hacked by <@2>!"
        );
    }
}
