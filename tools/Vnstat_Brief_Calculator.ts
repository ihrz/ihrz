// Types
interface VnStatData {
	vnstatversion: string;
	jsonversion: string;
	interfaces: Interface[];
}

interface Interface {
	name: string;
	traffic: {
		total: { rx: number; tx: number };
		fiveminute: TrafficEntry[];
		hour: TrafficEntry[];
		day: TrafficEntry[];
	};
}

interface TrafficEntry {
	timestamp: number;
	rx: number;
	tx: number;
}

interface Stats {
	avg: number;
	median: number;
	p95: number;
	p99: number;
	min: number;
	max: number;
	total: number;
}

// Utility functions
function formatBytes(bytes: number, decimals = 2): string {
	if (bytes === 0) return '0 B';
	const k = 1024;
	const sizes = ['B', 'KB', 'MB', 'GB', 'TB'];
	const i = Math.floor(Math.log(bytes) / Math.log(k));
	return parseFloat((bytes / Math.pow(k, i)).toFixed(decimals)) + ' ' + sizes[i];
}

function calculateStats(values: number[]): Stats {
	if (values.length === 0) {
		return { avg: 0, median: 0, p95: 0, p99: 0, min: 0, max: 0, total: 0 };
	}

	const sorted = [...values].sort((a, b) => a - b);
	const total = values.reduce((sum, val) => sum + val, 0);
	const avg = total / values.length;

	const getPercentile = (p: number) => {
		const index = Math.ceil((p / 100) * sorted.length) - 1;
		return sorted[index] || 0;
	};

	return {
		avg,
		median: getPercentile(50),
		p95: getPercentile(95),
		p99: getPercentile(99),
		min: sorted[0],
		max: sorted[sorted.length - 1],
		total
	};
}

function createBarChart(values: number[], labels: string[], width = 50, title = ''): string {
	const max = Math.max(...values);
	let chart = `\n${title}\n${'='.repeat(width + 20)}\n`;

	for (let i = 0; i < values.length; i++) {
		const barLength = Math.round((values[i] / max) * width);
		const bar = '█'.repeat(barLength);
		const padding = ' '.repeat(Math.max(0, 15 - labels[i].length));
		chart += `${labels[i]}${padding} ${bar} ${formatBytes(values[i])}\n`;
	}

	return chart;
}

