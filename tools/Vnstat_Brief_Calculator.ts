function groupByWeek(dayData: TrafficEntry[]): { rx: number[]; tx: number[]; labels: string[] } {
	const weeks: Map<string, { rx: number; tx: number }> = new Map();

	dayData.forEach(entry => {
		const date = new Date(entry.timestamp * 1000);
		const weekStart = new Date(date);
		weekStart.setDate(date.getDate() - date.getDay());
		const weekKey = weekStart.toISOString().split('T')[0];

		if (!weeks.has(weekKey)) {
			weeks.set(weekKey, { rx: 0, tx: 0 });
		}
		const week = weeks.get(weekKey)!;
		week.rx += entry.rx;
		week.tx += entry.tx;
	});

	const sorted = Array.from(weeks.entries()).sort((a, b) => a[0].localeCompare(b[0]));
	return {
		rx: sorted.map(([_, v]) => v.rx),
		tx: sorted.map(([_, v]) => v.tx),
		labels: sorted.map(([k]) => k)
	};
}

function groupByMonth(dayData: TrafficEntry[]): { rx: number[]; tx: number[]; labels: string[] } {
	const months: Map<string, { rx: number; tx: number }> = new Map();

	dayData.forEach(entry => {
		const date = new Date(entry.timestamp * 1000);
		const monthKey = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}`;

		if (!months.has(monthKey)) {
			months.set(monthKey, { rx: 0, tx: 0 });
		}
		const month = months.get(monthKey)!;
		month.rx += entry.rx;
		month.tx += entry.tx;
	});

	const sorted = Array.from(months.entries()).sort((a, b) => a[0].localeCompare(b[0]));
	return {
		rx: sorted.map(([_, v]) => v.rx),
		tx: sorted.map(([_, v]) => v.tx),
		labels: sorted.map(([k]) => k)
	};
}

// Main
async function main() {
	console.log(`\n📊 Network Traffic Analyzer`);
	console.log(`Paste your vnStat JSON data and press Ctrl+D (or Ctrl+Z on Windows) when done:\n`);

	const decoder = new TextDecoder();
	const reader = Bun.stdin.stream().getReader();
	let jsonInput = '';

	try {
		while (true) {
			const { done, value } = await reader.read();
			if (done) break;
			jsonInput += decoder.decode(value, { stream: true });
		}
	} finally {
		reader.releaseLock();
	}

	let data: VnStatData;
	try {
		data = JSON.parse(jsonInput.trim());
	} catch (error) {
		console.error(`❌ Error parsing JSON: ${error}`);
		console.error(`Make sure you pasted valid JSON data.`);
		process.exit(1);
	}

	if (!data.interfaces || data.interfaces.length === 0) {
		console.error(`❌ No network interfaces found in the data.`);
		process.exit(1);
	}

	const iface = data.interfaces[0];
	console.log(`\n📊 Network Traffic Analysis for interface: ${iface.name}`);
	console.log(`vnStat version: ${data.vnstatversion}`);

	// Total statistics
	console.log(`\n${'='.repeat(70)}`);
	console.log(`  TOTAL TRAFFIC`);
	console.log(`${'='.repeat(70)}`);
	console.log(`  Download (RX): ${formatBytes(iface.traffic.total.rx)}`);
	console.log(`  Upload (TX):   ${formatBytes(iface.traffic.total.tx)}`);
	console.log(`  Total:         ${formatBytes(iface.traffic.total.rx + iface.traffic.total.tx)}`);

	// Daily statistics
	const dayRx = iface.traffic.day.map(d => d.rx);
	const dayTx = iface.traffic.day.map(d => d.tx);
	printStats('DAILY STATISTICS', calculateStats(dayRx), calculateStats(dayTx));

	// Hourly statistics
	const hourRx = iface.traffic.hour.map(h => h.rx);
	const hourTx = iface.traffic.hour.map(h => h.tx);
	printStats('HOURLY STATISTICS', calculateStats(hourRx), calculateStats(hourTx));

	// Weekly statistics
	const weekData = groupByWeek(iface.traffic.day);
	printStats('WEEKLY STATISTICS', calculateStats(weekData.rx), calculateStats(weekData.tx));

	// Monthly statistics
	const monthData = groupByMonth(iface.traffic.day);
	printStats('MONTHLY STATISTICS', calculateStats(monthData.rx), calculateStats(monthData.tx));

	// Charts
	console.log(createBarChart(
		monthData.rx.slice(-6),
		monthData.labels.slice(-6),
		60,
		'📈 DOWNLOAD (RX) - LAST 6 MONTHS'
	));

	console.log(createBarChart(
		monthData.tx.slice(-6),
		monthData.labels.slice(-6),
		60,
		'📤 UPLOAD (TX) - LAST 6 MONTHS'
	));

	// Top 10 days with highest traffic
	const topDays = iface.traffic.day
		.map((d, i) => ({
			date: new Date(d.timestamp * 1000).toISOString().split('T')[0],
			rx: d.rx,
			tx: d.tx,
			total: d.rx + d.tx
		}))
		.sort((a, b) => b.total - a.total)
		.slice(0, 10);

	console.log(`\n${'='.repeat(70)}`);
	console.log(`  TOP 10 DAYS - TOTAL TRAFFIC`);
	console.log(`${'='.repeat(70)}`);
	topDays.forEach((day, i) => {
		console.log(`  ${i + 1}. ${day.date}  │  ${formatBytes(day.total).padEnd(15)} (↓${formatBytes(day.rx)} ↑${formatBytes(day.tx)})`);
	});
	console.log();
}

main().catch(console.error);