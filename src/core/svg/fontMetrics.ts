/*
 * Minimal TrueType reader: advance widths only (head, hhea, hmtx, cmap
 * formats 4 and 12). resvg has no text layout API usable for measuring
 * (one Resvg instance per measure costs ~200ms), so wrapping and ellipsis
 * are computed here from the same font files resvg renders with.
 * Kerning is ignored: the error is a few pixels on a full line, absorbed by
 * the margins of the layouts.
 */

import path from "path";

import glyphFallbacks from "./glyphFallbacks.json";

export type FontFamily =
	| "Noto Sans"
	| "JetBrains Mono"
	| "Rye"
	| "Anton"
	| ScriptFamily
	| GlyphFallbackFamily;
export type ScriptFamily =
	| "Noto Sans Arabic"
	| "Noto Sans Hebrew"
	| "Noto Sans JP"
	| "Noto Sans KR";
/** One of the families listed in glyphFallbacks.json. */
export type GlyphFallbackFamily = string & { readonly glyphFallback: true };
export type FontWeight = 400 | 700;

type NamedFamily = Exclude<FontFamily, GlyphFallbackFamily>;

// The families below src/assets/fonts/fallback, and which one draws what.
// Generated by tools/Font_Fallback_Generator.ts: ranges are flat
// [first, last, family index] triples, sorted, so a character never costs more
// than a binary search and only the fonts an image really uses get read.
const FALLBACK_FILES = new Map<string, string>(
	glyphFallbacks.families.map(({ family, file }) => [family, file])
);
const FALLBACK_NAMES = glyphFallbacks.families.map(({ family }) => family);
const FALLBACK_RANGES = glyphFallbacks.ranges;

export const FONT_DIR = path.join(process.cwd(), "src", "assets", "fonts");

// Family + weight -> file. Families are the names embedded in the files,
// which is what resvg matches `font-family` against.
const FONT_FILES: Record<NamedFamily, Partial<Record<FontWeight, string>>> = {
	"Noto Sans": { 400: "NotoSans-Regular.ttf", 700: "NotoSans-Bold.ttf" },
	"JetBrains Mono": {
		400: "JetBrainsMono-Regular.ttf",
		700: "JetBrainsMono-Bold.ttf"
	},
	Rye: { 400: "Rye-Regular.ttf" },
	// Open replacement for Impact (memes).
	Anton: { 400: "Anton-Regular.ttf" },
	// Script fonts: only loaded by resvg when the SVG uses them (the CJK
	// files are ~4.5 MB each and resvg parses its fonts on every render).
	"Noto Sans Arabic": {
		400: "NotoSansArabic-Regular.ttf",
		700: "NotoSansArabic-Bold.ttf"
	},
	"Noto Sans JP": { 400: "NotoSansJP-Regular.otf" },
	"Noto Sans KR": { 400: "NotoSansKR-Regular.otf" },
	"Noto Sans Hebrew": { 400: "fallback/NotoSansHebrew.ttf" }
};

const SCRIPT_FAMILIES: ScriptFamily[] = [
	"Noto Sans Arabic",
	"Noto Sans Hebrew",
	"Noto Sans JP",
	"Noto Sans KR"
];

// Script_Extensions, not Script: shared characters such as the katakana
// long vowel mark (U+30FC) or the Arabic tatweel are "Common" by Script.
const SCRIPT_PATTERNS: [ScriptFamily, RegExp][] = [
	["Noto Sans Arabic", /\p{Script_Extensions=Arabic}/u],
	// A script, not a glyph fallback: its words must keep their spaces in one
	// right-to-left run.
	["Noto Sans Hebrew", /\p{Script_Extensions=Hebrew}/u],
	[
		"Noto Sans JP",
		/[\p{Script_Extensions=Han}\p{Script_Extensions=Hiragana}\p{Script_Extensions=Katakana}\uff00-\uffef]/u
	],
	["Noto Sans KR", /\p{Script_Extensions=Hangul}/u]
];

/**
 * Script font needed for a grapheme, if any. resvg (2.6) keeps the first
 * fallback font for the rest of a text element and drops the whole element
 * when an Arabic tspan sits in it, so such text is drawn as separate runs,
 * each with its own font-family. The same goes for a character missing from
 * the base fonts, once prepareGlyphFallbacks has seen the text.
 */
export function scriptFamilyOf(grapheme: string): FontFamily | null {
	for (const [family, pattern] of SCRIPT_PATTERNS) {
		if (pattern.test(grapheme)) return family;
	}
	return glyphFallbackFamilyOf(grapheme.codePointAt(0)!);
}

// Missing glyphs fall back like resvg does: to the other bundled fonts.
const FALLBACK_ORDER: FontFamily[] = ["Noto Sans", "JetBrains Mono"];

interface ParsedFont {
	unitsPerEm: number;
	advances: Uint16Array;
	glyphOf(codePoint: number): number;
}

const parsed = new Map<string, Promise<ParsedFont>>();

export function parseFont(buffer: ArrayBuffer): ParsedFont {
	const view = new DataView(buffer);
	const tables = new Map<string, number>();
	const numTables = view.getUint16(4);
	for (let i = 0; i < numTables; i++) {
		const record = 12 + i * 16;
		const tag = String.fromCharCode(
			view.getUint8(record),
			view.getUint8(record + 1),
			view.getUint8(record + 2),
			view.getUint8(record + 3)
		);
		tables.set(tag, view.getUint32(record + 8));
	}

	const table = (tag: string) => {
		const offset = tables.get(tag);
		if (offset === undefined) throw new Error(`Font table ${tag} missing`);
		return offset;
	};

	const unitsPerEm = view.getUint16(table("head") + 18);
	const numberOfHMetrics = view.getUint16(table("hhea") + 34);
	const numGlyphs = view.getUint16(table("maxp") + 4);

	const hmtx = table("hmtx");
	const advances = new Uint16Array(numGlyphs);
	let last = 0;
	for (let glyph = 0; glyph < numGlyphs; glyph++) {
		if (glyph < numberOfHMetrics) last = view.getUint16(hmtx + glyph * 4);
		advances[glyph] = last;
	}

	return { unitsPerEm, advances, glyphOf: parseCmap(view, table("cmap")) };
}

function parseCmap(
	view: DataView,
	cmap: number
): (codePoint: number) => number {
	let format4 = -1;
	let format12 = -1;
	const count = view.getUint16(cmap + 2);
	for (let i = 0; i < count; i++) {
		const record = cmap + 4 + i * 8;
		const platform = view.getUint16(record);
		const encoding = view.getUint16(record + 2);
		const subtable = cmap + view.getUint32(record + 4);
		const format = view.getUint16(subtable);
		const unicode = platform === 0 || (platform === 3 && encoding !== 0);
		if (!unicode) continue;
		if (format === 12) format12 = subtable;
		else if (format === 4 && format4 === -1) format4 = subtable;
	}

	if (format12 !== -1) {
		const groups = view.getUint32(format12 + 12);
		return (codePoint) => {
			let low = 0;
			let high = groups - 1;
			while (low <= high) {
				const mid = (low + high) >> 1;
				const group = format12 + 16 + mid * 12;
				const start = view.getUint32(group);
				const end = view.getUint32(group + 4);
				if (codePoint < start) high = mid - 1;
				else if (codePoint > end) low = mid + 1;
				else return view.getUint32(group + 8) + codePoint - start;
			}
			return 0;
		};
	}

	if (format4 !== -1) {
		const segCount = view.getUint16(format4 + 6) / 2;
		const endCodes = format4 + 14;
		const startCodes = endCodes + segCount * 2 + 2;
		const idDeltas = startCodes + segCount * 2;
		const idRangeOffsets = idDeltas + segCount * 2;
		return (codePoint) => {
			if (codePoint > 0xffff) return 0;
			for (let i = 0; i < segCount; i++) {
				if (codePoint > view.getUint16(endCodes + i * 2)) continue;
				const start = view.getUint16(startCodes + i * 2);
				if (codePoint < start) return 0;
				const delta = view.getInt16(idDeltas + i * 2);
				const rangeOffsetAt = idRangeOffsets + i * 2;
				const rangeOffset = view.getUint16(rangeOffsetAt);
				if (rangeOffset === 0) return (codePoint + delta) & 0xffff;
				const glyph = view.getUint16(
					rangeOffsetAt + rangeOffset + (codePoint - start) * 2
				);
				return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
			}
			return 0;
		};
	}

	return () => 0;
}

function fileFor(family: FontFamily, weight: FontWeight): string {
	const fallback = FALLBACK_FILES.get(family);
	if (fallback) return path.join("fallback", fallback);

	const files = FONT_FILES[family as NamedFamily];
	return files[weight] ?? files[400] ?? FONT_FILES["Noto Sans"][400]!;
}

function loadFont(file: string): Promise<ParsedFont> {
	let font = parsed.get(file);
	if (!font) {
		font = Bun.file(path.join(FONT_DIR, file))
			.arrayBuffer()
			.then(parseFont);
		parsed.set(file, font);
	}
	return font;
}

let baseCoverage: { notoSans: ParsedFont; mono: ParsedFont } | null = null;

/** Must have run once before the runs of a text are computed. */
export async function prepareGlyphFallbacks(): Promise<void> {
	baseCoverage ??= {
		notoSans: await loadFont(fileFor("Noto Sans", 400)),
		mono: await loadFont(fileFor("JetBrains Mono", 400))
	};
}

function fallbackInRanges(codePoint: number): GlyphFallbackFamily | null {
	let low = 0;
	let high = FALLBACK_RANGES.length / 3 - 1;
	while (low <= high) {
		const mid = (low + high) >> 1;
		const at = mid * 3;
		if (codePoint < FALLBACK_RANGES[at]) high = mid - 1;
		else if (codePoint > FALLBACK_RANGES[at + 1]) low = mid + 1;
		else {
			return FALLBACK_NAMES[
				FALLBACK_RANGES[at + 2]
			] as GlyphFallbackFamily;
		}
	}
	return null;
}

function glyphFallbackFamilyOf(codePoint: number): FontFamily | null {
	if (!baseCoverage || baseCoverage.notoSans.glyphOf(codePoint) !== 0) {
		return null;
	}
	// resvg sticks to its first fallback font: never let it pick one.
	if (baseCoverage.mono.glyphOf(codePoint) !== 0) return "JetBrains Mono";

	return fallbackInRanges(codePoint);
}

/** True for the families picked per character, from the font contents. */
export function isGlyphFallback(family: FontFamily): boolean {
	return family === "JetBrains Mono" || FALLBACK_FILES.has(family);
}

/**
 * Whether a shared character (space, digit, punctuation) can stay in a run of
 * this family. Glyph fallback fonts often lack them or draw them oddly; the
 * script fonts keep what resvg has always done with them.
 */
export function canStayInRun(family: FontFamily, grapheme: string): boolean {
	return (
		!isGlyphFallback(family) ||
		glyphFallbackFamilyOf(grapheme.codePointAt(0)!) === family
	);
}

function filesOf(family: FontFamily): string[] {
	if (FALLBACK_FILES.has(family)) {
		return [path.join(FONT_DIR, fileFor(family, 400))];
	}
	return Object.values(FONT_FILES[family as NamedFamily])
		.filter((file): file is string => !!file)
		.map((file) => path.join(FONT_DIR, file));
}

const CORE_FILES = (Object.keys(FONT_FILES) as FontFamily[])
	.filter((family) => !SCRIPT_FAMILIES.includes(family as ScriptFamily))
	.flatMap((family) => filesOf(family as FontFamily));

/** Font files resvg must load for this SVG (absolute paths). */
export function fontFilesFor(svg: string): string[] {
	const files = [...CORE_FILES];
	// One pass over the document: it can hold megabytes of data URIs, and
	// there are far too many families to search for each of them.
	const used = new Set(
		[...svg.matchAll(/font-family="([^"]+)"/g)].map((match) => match[1])
	);
	for (const name of used) {
		const family = name as FontFamily;
		if (
			FALLBACK_FILES.has(family) ||
			SCRIPT_FAMILIES.includes(family as ScriptFamily)
		) {
			files.push(...filesOf(family));
		}
	}
	return files;
}

/** Every bundled font file (absolute paths). */
export function bundledFontFiles(): string[] {
	return [
		...(Object.keys(FONT_FILES) as FontFamily[]),
		...(FALLBACK_NAMES as FontFamily[])
	].flatMap(filesOf);
}

export interface Measurer {
	/** Width in px of `text` (no emoji) at `size`, letter spacing included. */
	width(text: string): number;
}

/** Loads (once) the fonts needed and returns a synchronous measurer. */
export async function measurer(
	family: FontFamily,
	weight: FontWeight,
	size: number,
	letterSpacing = 0
): Promise<Measurer> {
	const primary = await loadFont(fileFor(family, weight));
	const fallbacks = await Promise.all(
		FALLBACK_ORDER.filter((f) => f !== family).map((f) =>
			loadFont(fileFor(f, weight))
		)
	);

	const advance = (codePoint: number): number => {
		for (const font of [primary, ...fallbacks]) {
			const glyph = font.glyphOf(codePoint);
			if (glyph !== 0) return font.advances[glyph] / font.unitsPerEm;
		}
		// Not covered by the fonts of this run: average glyph width.
		return 0.6;
	};

	return {
		width(text: string): number {
			let em = 0;
			let glyphs = 0;
			for (const char of text) {
				em += advance(char.codePointAt(0)!);
				glyphs++;
			}
			return em * size + glyphs * letterSpacing;
		}
	};
}
